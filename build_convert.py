"""
Generates convert.js: a self-contained, dependency-free bidirectional Simplified<->Traditional
converter whose output is byte-for-byte identical to Python OpenCC (verified by tests/verify).

Source of truth = the SAME OpenCC dictionary .txt files used by build_dict.py's t2s pass, so
the runtime converter and the dict's stored 's' field can never disagree. A greedy longest-match
over (phrases + chars) reproduces OpenCC exactly (validated on 49k+ phrase keys, 0 mismatches).

Exceptions (e.g. Wu-specific 睏, which OpenCC merges into 困) come from simp_trad_overrides.json,
shared with build_dict.py.
"""
import os, json

OPENCC_DICT = '/opt/homebrew/lib/python3.14/site-packages/opencc/dictionary'
HERE = os.path.dirname(os.path.abspath(__file__))
OVERRIDES_FILE = os.path.join(HERE, 'simp_trad_overrides.json')
OUT = os.path.join(HERE, 'convert.js')


def load_first_candidate(path):
    """OpenCC entries are 'key\\tcand1 cand2 ...'; conversion always takes the first candidate.
    First occurrence wins (mirrors OpenCC loading phrases then chars into one group)."""
    m = {}
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if not line or '\t' not in line:
                continue
            k, v = line.split('\t', 1)
            m.setdefault(k, v.split(' ')[0])
    return m


def build_table(char_file, phrase_file):
    """Chars form the base; phrases override (longer keys win at match time anyway, but phrase
    values also take precedence for equal-length collisions - matching OpenCC's group order)."""
    table = load_first_candidate(os.path.join(OPENCC_DICT, char_file))
    for k, v in load_first_candidate(os.path.join(OPENCC_DICT, phrase_file)).items():
        table[k] = v
    return table


with open(OVERRIDES_FILE, encoding='utf-8') as f:
    ov = json.load(f)
invariant = set(ov.get('invariant', []))

s2t = build_table('STCharacters.txt', 'STPhrases.txt')
t2s = build_table('TSCharacters.txt', 'TSPhrases.txt')

# Apply explicit remaps, then strip any mapping that touches an invariant char so the runtime
# converter leaves it untouched (drop keys that ARE invariant, and any single-char key whose
# value would change an invariant char).
s2t.update(ov.get('s2t', {}))
t2s.update(ov.get('t2s', {}))
for ch in invariant:
    s2t.pop(ch, None)
    t2s.pop(ch, None)

s2t_max = max(len(k) for k in s2t)
t2s_max = max(len(k) for k in t2s)

# compact JSON (no spaces) to keep file size down; keys are already deduped
s2t_json = json.dumps(s2t, ensure_ascii=False, separators=(',', ':'))
t2s_json = json.dumps(t2s, ensure_ascii=False, separators=(',', ':'))
invariant_json = json.dumps(sorted(invariant), ensure_ascii=False, separators=(',', ':'))

js = f"""// AUTO-GENERATED by build_convert.py - do not edit by hand.
// Bidirectional Simplified<->Traditional converter, output-identical to Python OpenCC.
// Tables come from the same OpenCC dictionaries that build_dict.py uses, so this converter
// and dict.js's stored 's' field can never disagree. Exceptions in simp_trad_overrides.json.
const OPENCC_S2T = {s2t_json};
const OPENCC_T2S = {t2s_json};
const CONVERT_INVARIANT = new Set({invariant_json});
const OPENCC_S2T_MAX = {s2t_max};
const OPENCC_T2S_MAX = {t2s_max};

// Greedy longest-match, exactly reproducing OpenCC's MaxMatch conversion. Invariant chars
// (e.g. Wu-specific 睏) are emitted verbatim and never consumed as part of a longer key.
function _openccConvert(text, table, maxLen) {{
  if (!text) return text;
  let out = "";
  let i = 0;
  const n = text.length;
  while (i < n) {{
    if (CONVERT_INVARIANT.has(text[i])) {{ out += text[i]; i += 1; continue; }}
    let matched = false;
    const hi = Math.min(maxLen, n - i);
    for (let L = hi; L >= 1; L--) {{
      const seg = text.slice(i, i + L);
      const hit = table[seg];
      if (hit !== undefined) {{ out += hit; i += L; matched = true; break; }}
    }}
    if (!matched) {{ out += text[i]; i += 1; }}
  }}
  return out;
}}

// Simplified -> Traditional. This is the app's INTERNAL normalization direction (dict.js keys
// are traditional), so run arbitrary user input through this before dictionary lookup.
function toTraditional(text) {{ return _openccConvert(text, OPENCC_S2T, OPENCC_S2T_MAX); }}
// Traditional -> Simplified, for output when the user prefers simplified.
function toSimplified(text) {{ return _openccConvert(text, OPENCC_T2S, OPENCC_T2S_MAX); }}

if (typeof module !== "undefined" && module.exports) {{
  module.exports = {{ toTraditional, toSimplified, OPENCC_S2T, OPENCC_T2S, CONVERT_INVARIANT }};
}}
"""

with open(OUT, 'w', encoding='utf-8') as f:
    f.write(js)

print(f"[convert] s2t {len(s2t)} entries (maxkey {s2t_max}), t2s {len(t2s)} entries "
      f"(maxkey {t2s_max}), invariant {len(invariant)}")
print(f"[convert] wrote {OUT} ({os.path.getsize(OUT) // 1024} KB)")

